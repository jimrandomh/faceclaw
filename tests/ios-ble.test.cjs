test('full-frame RLE splits 65535-pixel runs and preserves opaque near-black', () => {
  const packed = p.packGray4(new Uint8Array(640 * 480).fill(1), 640, 480);
  assert.ok(packed.every(v => v === 0));
  const encoded = p.rle4(packed);
  let count = 0, offset = 0;
  while (offset < encoded.length) {
    const token = encoded[offset++]; let run = token >>> 4;
    if (!run) { run = encoded[offset++]; if (!run) { run = encoded[offset] | (encoded[offset + 1] << 8); offset += 2; } }
    assert.equal(token & 15, 0); count += run;
  }
  assert.equal(count, 640 * 480);
  assert.deepEqual(inflate(deflate(encoded)), encoded);
});

