test('negotiated-MTU framing reassembles split and coalesced notifications and rejects bad CRC', () => {
  const payload = p.concat(p.integer(1, 3), p.integer(2, 110), p.bytes(8, new Uint8Array(3900).fill(55)));
  const frames = p.frameMessage(payload, 0xe0, 0x20, 17, 185);
  assert.ok(frames.every(f => f.length <= 185));
  const receiver = new p.MessageReceiver(), stream = p.concat(...frames);
  assert.deepEqual(receiver.receive('L', stream.slice(0, 7)), []);
  const messages = receiver.receive('L', stream.slice(7));
  assert.equal(messages.length, 1); assert.deepEqual(messages[0].payload, payload);
  stream[stream.length - 1] ^= 1;
  assert.deepEqual(receiver.receive('L', stream), []);
  assert.throws(() => p.frameMessage(payload, 1, 0, 1, 10), /too small/);
  assert.throws(() => p.readBytes(new Uint8Array([0x1a, 0x7f]), 3), /Truncated/);
});

